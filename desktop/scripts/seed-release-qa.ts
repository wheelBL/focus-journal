import path from 'node:path';
import {readFileSync} from 'node:fs';
import {JournalService} from '../core/service';
import {SqliteJournalStore} from '../core/store';
import {localDate,shiftDate} from '../core/types';

const now=Date.now(),today=localDate(now),clock={time:now-7*86400000,now(){return this.time;},monotonic(){return this.time;}};
const version=JSON.parse(readFileSync('package.json','utf8')).version;
const file=path.resolve(`qa-data/release-${version}/journal.sqlite`),service=new JournalService(new SqliteJournalStore(file),clock,true);
if(service.snapshot().state.tasks.some(t=>t.id!=='inbox'))throw new Error('QA profile already has data; refusing to reseed.');
const add=(title:string,parentId:string|null='inbox',extra={})=>service.execute({type:'task.save',payload:{title,parentId,...extra}}).state.tasks.at(-1)!.id;
const root=add('专注记 · 第一轮试用',null);
service.execute({type:'outline.patch',payload:{id:root,field:'isProject',value:true}});
service.execute({type:'outline.patch',payload:{id:root,field:'description',value:'回到真实使用场景：是否容易开始，是否看得清下一步，以及结束后能否说清推进了什么。'}});
service.execute({type:'item-review.configure',payload:{id:root,enabled:true,nextDate:shiftDate(today,-7),interval:{unit:'weeks',count:1}}});
service.execute({type:'item-review.mark',payload:{id:root,batchId:'qa-first-review',note:'先按一周试用，回来检查流程是否顺畅。'}});
clock.time=now;
const subtree=add('验证任务树的日常操作',root,{estimateMinutes:60,dueAt:shiftDate(today,4)});
const child=add('检查查看、行内编辑与直接开始',subtree,{estimateMinutes:25,plannedDate:today});
const nested=add('核对标签与路径',child);
const completed=add('保留已有投入记录',root);
for(const id of [child,completed])service.execute({type:'item.focus',payload:{id,date:today}});
service.execute({type:'task.status',payload:{id:completed,status:'done'}});
const paused=add('评估下一轮扩展',root);service.execute({type:'item.change',payload:{id:paused,action:'pause'}});
const other=add('读书与个人整理',null);service.execute({type:'item.change',payload:{id:other,action:'pause'}});
for(const id of [subtree,other])service.execute({type:'item-review.configure',payload:{id,enabled:true,nextDate:today,interval:{unit:'weeks',count:1}}});
service.execute({type:'tag.attach',payload:{id:child,name:'试用'}});
service.execute({type:'tag.attach',payload:{id:nested,name:'检查'}});
const note=add('- 试用笔记：随时记录发现',root);
service.execute({type:'outline.patch',payload:{id:note,field:'description',value:'纯信息保留在树中，不需要估计、完成或计时。'}});
service.execute({type:'tag.attach',payload:{id:note,name:'参考'}});
service.execute({type:'session.manual',payload:{taskId:completed,date:shiftDate(today,-1),minutes:35,summary:'升级前后核对了任务和投入数量。'}});
service.execute({type:'outline.patch',payload:{id:'inbox',field:'isProject',value:false}});
service.execute({type:'outline.patch',payload:{id:nested,field:'dueAt',value:today}});
const routine=add('每日整理投入',root);
service.execute({type:'recurrence.set',payload:{id:routine,rule:{mode:'completion',unit:'day',interval:1,anchor:today,weekdays:[],until:null}}});
service.execute({type:'calendar.save',payload:{mode:'effort',taskId:child,start:new Date(`${shiftDate(today,-1)}T09:00`).toISOString(),end:new Date(`${shiftDate(today,-1)}T10:00`).toISOString(),summary:'从日历补记：检查任务树'}});
service.execute({type:'task.select',payload:{id:child}});
service.execute({type:'reminder.settings',payload:{settings:{sound:false,volume:60,repeatSeconds:30}}});
clock.time=now-15*60000;const free=service.execute({type:'focus.start-unassigned'}).timer!;clock.time+=5*60000;service.execute({type:'focus.stop',payload:{sessionId:free.sessionId}});
clock.time=now-5*60000;service.execute({type:'break.start',payload:{sessionId:free.sessionId}});clock.time=now;service.tick();
service.shutdown();console.log('Seeded isolated release QA profile.');
